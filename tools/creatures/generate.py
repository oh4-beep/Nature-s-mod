def camel(name):
    parts = name.split("_")
    return parts[0] + "".join(p.title() for p in parts[1:])


def f(x):
    x = float(x)
    if abs(x - round(x)) < 1e-6:
        return f"{int(round(x))}.0F"
    return f"{round(x, 4)}F"


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def write_json(path, data):
    write(path, json.dumps(data, indent=2) + "\n")


# --- java: models ----------------------------------------------------------------------------------

def emit_part(lines, parent, p, counter):
    var = f"p{counter[0]}"
    counter[0] += 1
    cubes = "CubeListBuilder.create()"
    for c in p["cubes"]:
        u, v = c["uv"]
        x, y, z = c["origin"]
        w, h, d = c["size"]
        cubes += f".texOffs({u}, {v})"
        if c["mirror"]:
            cubes += ".mirror()"
        if c["inflate"]:
            cubes += f".addBox({f(x)}, {f(y)}, {f(z)}, {f(w)}, {f(h)}, {f(d)}, new CubeDeformation({f(c['inflate'])}))"
        else:
            cubes += f".addBox({f(x)}, {f(y)}, {f(z)}, {f(w)}, {f(h)}, {f(d)})"
        if c["mirror"]:
            cubes += ".mirror(false)"
    px, py, pz = p["pivot"]
    rx, ry, rz = p["rot"]
    if any(abs(r) > 1e-9 for r in (rx, ry, rz)):
        pose = f"PartPose.offsetAndRotation({f(px)}, {f(py)}, {f(pz)}, {f(rx)}, {f(ry)}, {f(rz)})"
    else:
        pose = f"PartPose.offset({f(px)}, {f(py)}, {f(pz)})"
    lines.append(f"\t\tPartDefinition {var} = {parent}.addOrReplaceChild(\"{p['name']}\", {cubes}, {pose});")
    for child in p["children"]:
        emit_part(lines, var, child, counter)


def models_java(built):
    out = [HEADER, "package com.naturesmod.client.creature;\n",
           "import net.minecraft.client.model.geom.PartPose;",
           "import net.minecraft.client.model.geom.builders.CubeDeformation;",
           "import net.minecraft.client.model.geom.builders.CubeListBuilder;",
           "import net.minecraft.client.model.geom.builders.LayerDefinition;",
           "import net.minecraft.client.model.geom.builders.MeshDefinition;",
           "import net.minecraft.client.model.geom.builders.PartDefinition;\n",
           "/** Box models of the sea creatures, generated from their body plans. */",
           "@SuppressWarnings(\"unused\")",
           "final class CreatureModels {",
           "\tprivate CreatureModels() {",
           "\t}\n",
           "\tstatic LayerDefinition create(String species) {",
           "\t\treturn switch (species) {"]
    for sp, model in built:
        out.append(f"\t\t\tcase \"{sp['id']}\" -> {camel(sp['id'])}();")
    out.append("\t\t\tdefault -> throw new IllegalArgumentException(\"Unknown sea creature \" + species);")
    out.append("\t\t};")
    out.append("\t}\n")
    for sp, model in built:
        tw, th = model["tex"]
        out.append(f"\tprivate static LayerDefinition {camel(sp['id'])}() {{")
        out.append("\t\tMeshDefinition mesh = new MeshDefinition();")
        out.append("\t\tPartDefinition root = mesh.getRoot();")
        lines = []
        counter = [0]
        for p in model["root"]:
            emit_part(lines, "root", p, counter)
        out.extend(lines)
        out.append(f"\t\treturn LayerDefinition.create(mesh, {tw}, {th});")
        out.append("\t}\n")
    out.append("}")
    return "\n".join(out) + "\n"


# --- java: species table -------------------------------------------------------------------------------

CATEGORY_DEFAULT = {
    "school": "water_ambient", "passive": "water_ambient", "bottom": "water_ambient", "drifter": "water_ambient",
    "neutral": "water_creature", "ambush": "water_creature", "hunter": "water_creature", "pack": "water_ambient",
    "boss": "water_creature",
}


def world(sp):
    """Where a species lives: the seas (the Overworld's and the Abyss's), the new End, or the Overworld's lands and skies."""
    if sp["medium"] == "water":
        return "sea"
    return "end" if any(h.startswith("end_") for h in sp["habitats"]) or not sp["habitats"] else "overworld"


def seat(sp, model):
    """How high a rider sits on a creature that can be saddled, in blocks; 0 for one that cannot."""
    if not sp["ride"]:
        return 0.0
    return round(model["seat"] / 16.0 * sp["scale"], 3)


def category(sp):
    if sp["category"]:
        return sp["category"]
    if world(sp) == "overworld":
        # The Overworld's beasts and birds are animals like any other; its predators come out at night.
        return "monster" if sp["behavior"] in ("hunter", "ambush", "pack") else "creature"
    if sp["medium"] != "water":
        # The creatures of the End: its hunters are monsters, the rest come and go like bats.
        return "monster" if sp["behavior"] in ("hunter", "ambush", "pack", "boss") else "ambient"
    if sp["behavior"] in ("passive", "bottom") and sp["scale"] >= 1.3:
        return "water_creature"
    return CATEGORY_DEFAULT[sp["behavior"]]


def hitbox(sp, model):
    if sp["hitbox"]:
        return sp["hitbox"]
    length = model["length"] / 16.0 * sp["scale"]
    if sp["plan"] in ("jelly",):
        return (0.6 * sp["scale"] + 0.2, 0.8 * sp["scale"] + 0.2)
    if sp["plan"] == "seahorse":
        return (0.3 * sp["scale"] + 0.15, 0.8 * sp["scale"])
    if sp["plan"] == "ray":
        return (min(3.5, 1.0 * sp["scale"]), 0.25 * sp["scale"] + 0.1)
    width = min(3.5, max(0.3, length * 0.5))
    height = max(0.25, 0.45 * sp["scale"] * (1.4 if sp["plan"] == "deep" else 1.0))
    return (round(width, 2), round(min(height, 2.5), 2))


def default_health(sp):
    return sp["health"] or max(3, round(4 * sp["scale"] ** 2))


def species_java(built):
    out = [HEADER, "package com.naturesmod.creature;\n",
           "import java.util.List;\n",
           "/** Every Nature's Mod sea creature, generated from tools/creatures/species.py. */",
           "public final class CreatureSpecies {",
           "\tprivate CreatureSpecies() {",
           "\t}\n",
           "\tpublic static final List<SpeciesData> ALL = List.of("]
    rows = []
    for sp, model in built:
        w, h = hitbox(sp, model)
        biomes = list(dict.fromkeys(b for hb in sp["habitats"] for b in species_mod.HABITATS[hb]))
        habitats = ", ".join(f'"{b}"' for b in biomes)
        rows.append(
            f"\t\tnew SpeciesData(\"{sp['id']}\", \"{sp['plan']}\", Behavior.{sp['behavior'].upper()}, \"{category(sp)}\", "
            f"{f(sp['scale'])}, {f(w)}, {f(h)}, {float(default_health(sp))}, {float(sp['attack'])}, {float(sp['speed'])}, "
            f"{sp['group'][0]}, {sp['group'][1]}, {sp['weight']}, {str(sp['bucket']).lower()}, {str(bool(sp['glow'])).lower()}, "
            f"{str(sp['translucent']).lower()}, \"{sp['depth']}\", \"{sp['sound']}\", "
            f"{model.get('segments', 0)}, List.of({habitats}), \"{sp['effect']}\", \"{sp['medium']}\", {f(seat(sp, model))}, "
            f"\"{world(sp)}\")")
    out.append(",\n".join(rows))
    out.append("\t);")
    out.append("}")
    return "\n".join(out) + "\n"


